-- Immutable approval audit; ordinary application SQL UPDATE/DELETE is rejected.
CREATE FUNCTION "editorial_synopsis_approval_block_rewrite"() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'EditorialSynopsisApproval is append-only' USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "EditorialSynopsisApproval_append_only"
  BEFORE UPDATE OR DELETE ON "EditorialSynopsisApproval"
  FOR EACH ROW EXECUTE FUNCTION "editorial_synopsis_approval_block_rewrite"();

-- Evidence cannot be rewritten or deleted once verified; a one-way revocation
-- is allowed so previously valid evidence can be disabled, never silently restored.
CREATE FUNCTION "editorial_synopsis_evidence_revocation_only"() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD."revokedAt" IS NULL AND NEW."revokedAt" IS NOT NULL
     AND (to_jsonb(NEW) - 'revokedAt') = (to_jsonb(OLD) - 'revokedAt') THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'EditorialSynopsisEvidence is immutable except revocation' USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "EditorialSynopsisEvidence_revocation_only"
  BEFORE UPDATE OR DELETE ON "EditorialSynopsisEvidence"
  FOR EACH ROW EXECUTE FUNCTION "editorial_synopsis_evidence_revocation_only"();
