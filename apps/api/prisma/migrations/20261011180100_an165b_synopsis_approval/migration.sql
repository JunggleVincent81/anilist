  ("action" = 'SUBMIT' AND "fromState" = 'DRAFT' AND "toState" = 'SUBMITTED') OR
  ("action" = 'BEGIN_REVIEW' AND "fromState" = 'SUBMITTED' AND "toState" = 'UNDER_REVIEW') OR
